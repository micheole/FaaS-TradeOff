import random
import subprocess
import yaml
import os

def generate_random_sequence(i1_value, i2_value, config_path):
    """
    Generates a random sequence of I1 and I2 values based on configuration.

    Args:
        i1_value: The value to use for I1.
        i2_value: The value to use for I2.
        config_path: Path to the YAML configuration file.

    Returns:
        A list representing the randomized sequence.
    """

    with open(config_path, 'r') as file:
        config = yaml.safe_load(file)

    mode = config['mode']

    if mode in ["call-limited", "time-limited"]:
        num_trials = config['duration'] * config['arrival_rate']
    elif mode in ["accuracy-limited", "money-limited"]:
        num_trials = config['arrival_count'] * config['max_batches']
    else:
        raise ValueError(f"Unsupported mode: {mode}")

    sequence = []
    for _ in range(num_trials):
        sequence.append(random.choice([i1_value, i2_value]))

    return sequence

def run_orchestrator_with_sequence(i1_value, i2_value):
    """
    Runs the orchestrator with the sequence generated by the above function.

    Args:
        i1_value: The value to use for I1.
        i2_value: The value to use for I2.
    """
    config_dir = "configurations"
    for filename in os.listdir(config_dir):
        if filename.endswith(".yaml"):
            config_path = os.path.join(config_dir, filename)
            sequence = generate_random_sequence(i1_value, i2_value, config_path)
            mode = filename.split(".")[0] #get the mode, from the filename.
            print(f"Generated sequence for {mode}: {sequence}") #print the sequence
            # Run the orchestrator with the chosen sequence
            subprocess.run(["./orchestrator.sh", mode, str(i1_value), str(i2_value), str(sequence)])
            # print(f"Ran: ./orchestrator.sh {mode} {i1_value} {i2_value} {sequence}")